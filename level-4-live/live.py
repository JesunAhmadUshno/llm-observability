"""Level 4 Live: real-traffic observation plumbing, stdlib only.

This module is the live counterpart of the simulated levels. It talks
to a real model server (llama.cpp serving a local GGUF model over its
OpenAI-compatible HTTP API), times every call with a wall clock, and
persists records and spans through the Level 2 LogStore, so the live
evidence lands in exactly the same shape as the simulated evidence.

Honest labels, stated up front:
- The model is real and local: completions are generated by the model
  server at request time, never canned.
- Token counts come from the model server's own usage field. If that
  field is ever absent, the recorder falls back to the server's
  /tokenize endpoint and marks the record token_source accordingly.
- Cost is 0 by construction: the model is self-hosted, so the live
  price table below carries zero rates. That is a stated accounting
  choice, not a market price.
- The workload is driven by client.py in this folder: a program
  asking genuine questions about the bundled documents (corpus.json).
  It is a shipped workload driver, not organic user traffic, and the
  results file says so.
"""
import json
import os
import sys
import time
import urllib.request
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
for _d in (os.path.join(ROOT, "level-1-learn"), os.path.join(ROOT, "level-2-build")):
    if _d not in sys.path:
        sys.path.insert(0, _d)

from observability import Tracer, compute_cost, prompt_hash  # noqa: E402

__all__ = [
    "LIVE_PRICE_TABLE",
    "MODEL_NAME",
    "MODEL_VERSION",
    "PROMPT_VERSION",
    "LiveRecorder",
    "ModelClient",
    "WallClock",
    "answer_check",
    "build_prompt",
    "load_corpus",
]

MODEL_NAME = "qwen2.5-0.5b-instruct-q4_k_m"
MODEL_VERSION = "llama.cpp-b12418-local"
PROMPT_VERSION = "doc-qa-v1"
SYSTEM_PROMPT = "Answer the question using only the document. Be brief."

# Self-hosted local inference has no per-token price. The zero rates
# are an accounting statement, not a price quote.
LIVE_PRICE_TABLE = {MODEL_NAME: {"input_per_1k": 0.0, "output_per_1k": 0.0}}


def utc_now_iso():
    return datetime.now(timezone.utc).isoformat()


class WallClock:
    """Monotonic wall clock in whole milliseconds, for the Tracer."""

    def __init__(self):
        self._t0 = time.monotonic()

    def now(self):
        return int((time.monotonic() - self._t0) * 1000)


class ModelClient:
    """Minimal client for a llama.cpp server's OpenAI-style API."""

    def __init__(self, base_url, timeout_s=120):
        self.base_url = base_url.rstrip("/")
        self.timeout_s = timeout_s

    def _post(self, path, body):
        req = urllib.request.Request(
            self.base_url + path,
            data=json.dumps(body).encode("utf-8"),
            headers={"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=self.timeout_s) as resp:
            return json.loads(resp.read().decode("utf-8"))

    def chat(self, messages, max_tokens=160):
        payload = self._post("/v1/chat/completions", {
            "messages": messages,
            "max_tokens": max_tokens,
            "temperature": 0,
        })
        text = payload["choices"][0]["message"]["content"]
        usage = payload.get("usage") or {}
        return {
            "completion_text": text,
            "prompt_tokens": int(usage.get("prompt_tokens", 0)),
            "completion_tokens": int(usage.get("completion_tokens", 0)),
            "usage_present": bool(usage),
        }

    def tokenize(self, text):
        payload = self._post("/tokenize", {"content": text})
        return len(payload.get("tokens", []))


def load_corpus(path=None):
    path = path or os.path.join(HERE, "corpus.json")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def iter_questions(corpus):
    """Flat list of (document, question) pairs in corpus order."""
    pairs = []
    for doc in corpus["documents"]:
        for question in doc["questions"]:
            pairs.append((doc, question))
    return pairs


def build_prompt(document, question):
    return "Document:\n" + document["text"] + "\n\nQuestion: " + question["question"]


def answer_check(completion_text, expected_answer):
    """Mechanical check: the expected answer string appears in the
    completion (case-insensitive). This measures whether the model
    surfaced the answer that is in the document it was given. It is
    not a human quality judgement and is never labelled as one."""
    if not completion_text:
        return False
    return expected_answer.lower() in completion_text.lower()


class LiveRecorder:
    """Runs one real model call per ask and persists the record.

    Model errors are data, not crashes: a failed call is recorded with
    status "error" and the exception summary, so the error rate in the
    results comes from the same store as everything else.
    """

    def __init__(self, store, model_client):
        self.store = store
        self.model_client = model_client

    def ask(self, request_id, document, question):
        prompt_text = build_prompt(document, question)
        messages = [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt_text},
        ]
        tracer = Tracer(WallClock().now)
        status = "ok"
        error = None
        completion_text = ""
        prompt_tokens = 0
        completion_tokens = 0
        token_source = "usage"
        with tracer.span("request:" + str(request_id)):
            with tracer.span("prepare"):
                pass
            with tracer.span("model_call:" + MODEL_NAME):
                try:
                    out = self.model_client.chat(messages)
                    completion_text = out["completion_text"]
                    prompt_tokens = out["prompt_tokens"]
                    completion_tokens = out["completion_tokens"]
                    if not out["usage_present"]:
                        token_source = "tokenize-fallback"
                        prompt_tokens = self.model_client.tokenize(
                            SYSTEM_PROMPT + "\n" + prompt_text)
                        completion_tokens = self.model_client.tokenize(completion_text)
                except Exception as exc:  # a failed call is a recorded outcome
                    status = "error"
                    error = type(exc).__name__ + ": " + str(exc)[:200]
        spans = tracer.spans()
        root_span = [s for s in spans if s["parent_id"] is None][0]
        record = {
            "request_id": request_id,
            "timestamp_utc": utc_now_iso(),
            "prompt": prompt_text,
            "prompt_hash": prompt_hash(prompt_text),
            "model": MODEL_NAME,
            "prompt_tokens": prompt_tokens,
            "completion_tokens": completion_tokens,
            "total_tokens": prompt_tokens + completion_tokens,
            "cost_usd": compute_cost(MODEL_NAME, prompt_tokens,
                                     completion_tokens, LIVE_PRICE_TABLE),
            "latency_ms": root_span["duration_ms"],
            "prompt_version": PROMPT_VERSION,
            "model_version": MODEL_VERSION,
            "completion_text": completion_text,
            "trace_root_span_id": root_span["span_id"],
            "span_count": len(spans),
            "status": status,
            "error": error,
            "answer_check_pass": answer_check(completion_text,
                                              question["expected_answer"]),
            "document_id": document["id"],
            "question_id": question["id"],
            "token_source": token_source,
            "prompt_chars": len(prompt_text),
            "completion_chars": len(completion_text),
        }
        self.store.append_record(record)
        self.store.append_spans(spans)
        result = dict(record)
        result["spans"] = spans
        return result
